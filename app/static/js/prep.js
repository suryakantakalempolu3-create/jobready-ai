$("#genBtn").addEventListener("click", (e) => withLoading(e.currentTarget, async () => {
  const body = { role: $("#role").value, type: $("#type").value, count: +$("#count").value };
  if (!body.role.trim()) return toast("Enter a job role.", "err");
  const d = await api("/api/prep/questions", { method: "POST", body });
  const s = $("#src"); s.hidden = false; s.textContent = d.source === "ai" ? "Generated by AI" : "From built-in question bank";
  $("#out").innerHTML = d.questions.map((q, i) => `<details ${i === 0 ? "open" : ""}><summary>${i + 1}. ${esc(q.question)} ${q.type ? `<span class="badge blue">${esc(q.type)}</span>` : ""}</summary>
    <p class="muted small" style="margin-bottom:2px"><b>Sample answer</b></p><p>${esc(q.sample_answer)}</p>
    ${q.keywords?.length ? `<div class="chips">${q.keywords.map(k => `<span class="chip">${esc(k)}</span>`).join("")}</div>` : ""}</details>`).join("");
}));
